function strip(source, path) {
  const out = source
    .replace(/^import[\s\S]*?from\s+'[^']+';\n/gm, '')
    // `export async function` and `export default` exist too; matching only the four simple forms
    // let an `export` survive into the bundle, which the collision guard then reported.
    .replace(/^export\s+default\s+/gm, '')
    .replace(/^export\s+(?=(async\s+function|const|function|let|class|var))/gm, '');
  if (/^\s*(import|export)\b/m.test(out)) {
    throw new Error(`${path}: an import/export survived the strip; the build would be invalid`);
  }
  return out;
}

/**
 * Catch duplicate top-level declarations before they reach a browser.
 *
 * Concatenation has no module scope, so two modules each declaring `const NONE` produce a bundle that
 * throws on load. Module boundaries hid it in tests and only `node --check` on the bundle caught it.
 */
function collisions(text) {
  const counts = new Map();
  for (const line of text.split('\n')) {
    const m = line.match(/^(?:const|let|function|class)\s+([A-Za-z_$][\w$]*)/);
    if (!m) continue;
    counts.set(m[1], (counts.get(m[1]) || 0) + 1);
  }
  return [...counts.entries()].filter(([, n]) => n > 1).map(([name]) => name);
}

const bundle = [
  '// Generated by tools/build.mjs. Edit the files in src/ instead.',
  "(function () {\n'use strict';",
  ...ORDER.map((path) => `\n// ---- ${path} ----\n${strip(readFileSync(join(root, path), 'utf8'), path)}`),
  '})();',
].join('\n');

const clashes = collisions(bundle);
if (clashes.length) {
  throw new Error(`duplicate top-level declarations in the bundle: ${clashes.join(', ')}`);
}

mkdirSync(join(root, 'ext'), { recursive: true });
writeFileSync(join(root, 'ext/jevim.js'), bundle);
console.log(`ext/jevim.js  ${bundle.length} bytes from ${ORDER.length} modules`);
