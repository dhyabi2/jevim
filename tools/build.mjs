// A content script cannot be an ES module, and a bundler is a dependency this project does
// not need. The sources are written so that concatenating them in dependency order and
// dropping the import/export keywords produces a valid classic script.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

