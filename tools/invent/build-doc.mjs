// Assemble the verified inventions into one document, grouped by mechanism family.
//
// Grouping by family is deliberate honesty: these are not 110 unrelated ideas. They are a
// smaller number of mechanisms, each applied to domains that differ in buyer, price point and
// regulatory shape. Both numbers are stated, because "110 inventions" alone would overstate it
// and "17 mechanisms" alone would understate what is separately sellable.

import { readFileSync, writeFileSync } from 'node:fs';

const wave1 = JSON.parse(readFileSync('.ledger/invent/prefiltered.json', 'utf8'));
const wave2 = JSON.parse(readFileSync('.ledger/invent/wave2.json', 'utf8'));
const byId = new Map([...wave1, ...wave2].map((x) => [x.id, x]));

const verdicts = {};
for (const f of ['verdicts-001', 'verdicts-002', 'verdicts-003', 'verdicts-004']) {
  Object.assign(verdicts, JSON.parse(readFileSync(`.ledger/invent/${f}.json`, 'utf8')));
}

const FAMILY = {
  grep: 'Semantic match over a stream, emitting only what hits',
  'diff / patch': 'Compute a minimal change set, then apply it elsewhere',
  'git bisect': 'Binary search a history, with the model as the oracle',
  make: 'Staleness: recompute only what a change invalidated',
  find: 'Walk a tree by arbitrary predicate, then act',
  comm: 'Three-way set comparison: in both, left only, right only',
  'sort | uniq -c': 'Canonicalise, group, count, rank',
  jq: 'Reshape any input into a target schema without per-format training',
  iptables: 'Ordered rule chains with targets and a default policy',
  'chmod / ACLs': 'Per-object authority bits an auditor can read',
  tee: 'Fork to an immutable archive without touching the live path',
  fsck: 'Walk a structure, report its own inconsistencies, propose repairs',
  strace: 'An ordered causal trace that explains an outcome',
  ldd: 'Resolve the full transitive dependency closure',
  sed: 'Reviewable pattern substitution, applied in bulk',
  awk: 'Pattern-action rules that generalise across records',
  vim: 'A finite modal grammar for high-volume repetitive decisions',
  cron: 'Unattended recurring execution that re-resolves its own targets',
};

const accepted = Object.entries(verdicts)
  .filter(([, v]) => v.v === 'accept')
  .map(([id, v]) => ({ ...byId.get(id), id, why: v.r }))
  .filter((x) => x.name);

const groups = new Map();
for (const idea of accepted) {
  const key = FAMILY[idea.a] ? idea.a : 'other';
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(idea);
}
const ordered = [...groups.entries()].sort((a, b) => b[1].length - a[1].length);

const rejected = Object.values(verdicts).filter((v) => v.v === 'reject').length;
const judged = Object.keys(verdicts).length;

const out = [];
out.push(`# 110 verified inventions

Generated by the formula, then verified by hand. Every entry below passed three rules:

1. **New** — not a shipping product. Each entry names the closest thing that does ship and why it
   is not the same.
2. **Better** — it beats current practice on a stated axis.
3. **Paid** — a named buyer with a budget, and a price.

## The formula

    A  an old, proven, free tool whose DESIGN is a judgement-shaped operation,
       and whose reach was limited because it could only match text, never meaning
    B  a task that is expensive because a human must supply that judgement
    Z  A's design applied to B, with a model supplying the judgement

## What the numbers are

| | |
|---|---|
| candidates generated | 591 |
| survived structural filtering | ${wave2.length} in the judged wave, from 591 raw |
| judged by hand | ${judged} |
| **accepted** | **${accepted.length}** |
| rejected | ${rejected} |

**Read this before quoting the number.** These are not 110 unrelated inventions. They are
**${ordered.length} mechanisms** applied across domains that differ in buyer, price point and
regulatory shape. That is how vertical software actually works — the same idea sold into medical
coding and into e-discovery is two companies, not one — but anyone quoting the headline number
without saying "across ${ordered.length} mechanism families" is overstating it.

The families with the most entries are the ones whose design is most obviously a judgement:
walking a tree by predicate, binary search with an oracle, staleness, and three-way set
comparison. The thinnest are the ones where the borrowed name mostly described plumbing.

The most common reasons I rejected things: the mechanism was already a shipping product
(Browserbase for sessions, Launchable for test impact, Firecrawl for extraction, iManage for
versioning); the idea was infrastructure with no judgement in it (bounded parallelism, delta
transfer, event subscription); the borrowed name did no work (a metaphor with no mechanism); or
the buyer had no budget line (documentation, developer convenience).

---
`);

for (const [family, ideas] of ordered) {
  out.push(`\n## ${family} — ${FAMILY[family] || 'other'}\n`);
  out.push(`${ideas.length} product${ideas.length === 1 ? '' : 's'}.\n`);
  for (const i of ideas) {
    out.push(`### ${i.name} · ${i.b}

${i.one_line}

- **Mechanism** ${i.mechanism}
- **Endpoint** \`${i.endpoint || 'n/a'}\`
- **Closest existing** ${i.closest_existing || 'not stated'} — ${i.why_not_the_same || ''}
- **Wins on** ${i.better_axis}
- **Buyer** ${i.buyer}
- **Price** ${i.pricing}
- **Margin** ${i.unit_economics || 'not stated'}
- **Falsifier** ${i.falsifier}
- **Why I accepted it** ${i.why}
`);
  }
}

out.push(`
---

## What is not verified here

Each entry's *claim* was checked for novelty, a better axis and a payer. None of the numbers in
the "wins on" lines were measured — they are the generator's estimates and should be treated as
hypotheses. The falsifier line exists so each one can be tested cheaply before anything is built.

Nor is the market check exhaustive: I rejected on vendors I know ship the thing, which means the
survivors are "I could not name an incumbent", not "no incumbent exists". Before building any of
these, the first hour goes on a real competitive search for that one idea.
`);

writeFileSync('INVENTIONS.md', out.join('\n'));
console.log(`INVENTIONS.md: ${accepted.length} accepted across ${ordered.length} families`);
for (const [f, ideas] of ordered) console.log(`  ${String(ideas.length).padStart(2)}  ${f}`);
