// The formula, made explicit so the model cannot drift into generic SaaS ideas.
//
//   A = an old, proven, free tool whose DESIGN is a judgement-shaped operation, and whose reach
//       was limited because it could only match text, never meaning.
//   B = a task that is expensive because a human must supply that judgement.
//   Z = A's design applied to B, with a model supplying the judgement.
//
// The A list was cut from 35 to these after judging one round: tools whose design is really
// session or state infrastructure (tmux, screen, chroot, tar, dd, logrotate, at, nice, rsync)
// produced a duplicate cluster of ideas that are already commodity products - persistence,
// sandboxing, concurrency. The ones left are the operations where a decision happens.
export const A_TOOLS = [
  ['grep', 'match a pattern across a stream and emit only the lines that hit'],
  ['diff / patch', 'compute a minimal change set, then apply it elsewhere'],
  ['git bisect', 'binary search a history for the change that introduced a property - needs an oracle'],
  ['make', 'declare targets and dependencies, then rebuild only what is stale'],
  ['find', 'walk a tree, select by predicate, act on the matches'],
  ['comm', 'compare two sorted sets: in both, left only, right only'],
  ['sort | uniq -c', 'canonicalise, group, count, rank by frequency'],
  ['jq', 'query and reshape a structured document with a small composable language'],
  ['iptables', 'declarative chained rules that accept, drop or redirect'],
  ['chmod / ACLs', 'per-object permission bits an auditor can read'],
  ['tee', 'fork a stream so one copy is archived without disturbing the one that flows on'],
  ['fsck', 'walk a structure, find inconsistencies, propose repairs'],
  ['watch', 'rerun and diff, so what you see is only what changed'],
  ['strace', 'trace what a process actually did, in order, to explain an outcome'],
  ['ldd', 'resolve the full transitive dependency closure and report it'],
  ['sed', 'match, substitute, in place, scriptable, reviewable'],
  ['awk', 'per-record field extraction driven by pattern-action rules'],
  ['vim', 'modal grammar: operator + motion + object, every slot a finite enumeration'],
  ['man pages', 'terse uniform reference per unit, always in the same shape'],
  ['xargs', 'turn a list into bounded parallel invocations'],
];

