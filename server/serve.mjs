// Lightweight HTTP server. Node's own http module, no framework.
//   node server/serve.mjs [port]

import { createServer } from 'node:http';
import * as api from './api.mjs';
import * as uc from './usecases.mjs';

const PORT = Number(process.argv[2] || process.env.PORT || 8787);

const ROUTES = {
  'POST /v1/index': api.index,
  'POST /v1/keys': api.keys,
  'POST /v1/task': api.task,
  'POST /v1/session': api.openStream,
  'POST /v1/session/key': api.streamKey,
  'POST /v1/session/close': api.closeStream,

  // The five use cases, all readers of the same core.
  'POST /v1/ground': uc.ground,
  'POST /v1/form/fill': uc.formFill,
  'POST /v1/navigate/survey': uc.navigateSurvey,
  'POST /v1/task': uc.taskCompile,
  'POST /v1/task/replay': uc.taskReplay,
  'POST /v1/script/author': uc.scriptAuthor,
  'POST /v1/script/run': uc.scriptRun,
  'POST /v1/test/run': uc.testRun,
};

const HELP = {
  service: 'jevim',
  version: '0.1.0',
  tiers: { L0: 'cached binding, 0 ms, no network',
           L1: 'one Jev call, ~656 ms, primed by type-ahead while the query is typed',
           L2: 'agent (not built)' },
  endpoints: {
    'POST /v1/index': '{url} -> the element index, and what it costs in tokens',
    'POST /v1/keys': '{url, keys, bindings?} -> what the grammar did, keystroke by keystroke',
    'POST /v1/task': '{start, steps[]} -> a whole task; steps are keys / pick / type / follow / extract / report',
    'POST /v1/session': '{url} -> {session}: open a streaming session',
    'POST /v1/session/key': '{session, token} -> one keystroke at a time; each character of a query primes the resolver',
    'POST /v1/session/close': '{session}',
    'POST /v1/ground': '{url, intent} -> one element with a confidence, or a refusal with a reason',
    'POST /v1/form/fill': '{url, values} -> what was placed and what needs a human; never mis-fills',
    'POST /v1/navigate/survey': '{url} -> page kind, next page, consent wall, login, paywall, in ONE model call',
    'POST /v1/task': '{url, task} -> describe a task in English; it runs once and returns a pinned artifact',
    'POST /v1/task/replay': '{url, script} -> replay that artifact with zero model calls and an identical trace',
    'POST /v1/script/author': '{url, task} -> a motion script generated by the L2 model and screened by Jev',
    'POST /v1/script/run': '{url, script, values?} -> replay a motion script; pinned steps cost nothing',
    'POST /v1/test/run': '{url, script} -> the same replay read as a test verdict',
  },
  typeAhead: 'A one-shot request carries the whole motion, so there is no typing time to hide the '
           + 'resolver inside. Stream keystrokes through /v1/session/key to get the answer before <CR>.',
  note: 'Headless: jsdom has no layout engine, so geometry-based visibility rules are heuristic here. '
      + 'Responses carry layout:"synthetic" to say so.',
};

createServer(async (req, res) => {
  const route = `${req.method} ${req.url.split('?')[0]}`;
  const send = (code, body) => {
    const text = JSON.stringify(body, null, 1);
    res.writeHead(code, { 'content-type': 'application/json', 'content-length': Buffer.byteLength(text) });
    res.end(text);
  };

  if (route === 'GET /' || route === 'GET /v1') return send(200, HELP);

  const handler = ROUTES[route];
  if (!handler) return send(404, { error: 'no such endpoint', try: Object.keys(ROUTES) });

  let body = '';
  for await (const chunk of req) body += chunk;

  try {
    const started = Date.now();
    const result = await handler(body ? JSON.parse(body) : {});
    send(200, { ...result, elapsedMs: Date.now() - started });
  } catch (error) {
    send(400, { error: String(error && error.message || error) });
  }
}).listen(PORT, process.env.JEVIM_HOST || '0.0.0.0', () => console.log(`jevim api on http://${process.env.JEVIM_HOST || '0.0.0.0'}:${PORT}`));
